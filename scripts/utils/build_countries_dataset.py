#!/usr/bin/env python3
"""Rebuild cv-analyzer-frontend/src/lib/countries.ts — the country list behind
the careers apply form's "Nationality" picker (and the resulting Nationality
filter on the applicants/database pages).

Source: GeoNames' countryInfo.txt (public domain / CC-BY 4.0,
https://www.geonames.org/ — credit: GeoNames), the standard ISO 3166
country/territory list (~250 entries). Small and stable enough to bundle
directly in the frontend rather than serving it from a backend endpoint —
unlike cities.json (33k+ raw entries needing curation), there's no
duplication/neighbourhood problem to filter out here.

Run:  python scripts/utils/build_countries_dataset.py
"""
import sys
import urllib.request
from pathlib import Path

COUNTRY_INFO_URL = "https://download.geonames.org/export/dump/countryInfo.txt"
OUTPUT_PATH = (
    Path(__file__).resolve().parents[2]
    / "cv-analyzer-frontend" / "src" / "lib" / "countries.ts"
)


def main() -> None:
    print(f"Downloading {COUNTRY_INFO_URL} ...", file=sys.stderr)
    with urllib.request.urlopen(COUNTRY_INFO_URL, timeout=30) as resp:
        raw = resp.read().decode("utf-8")

    countries = []
    for line in raw.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        cols = line.split("\t")
        countries.append(cols[4])
    countries.sort()

    ts_list = ",\n  ".join(f'"{c}"' for c in countries)
    content = f"""// Auto-generated by scripts/utils/build_countries_dataset.py — do not hand-edit.
// Source: GeoNames countryInfo.txt (public domain / CC-BY 4.0, https://www.geonames.org/).
// Used by NationalityAutocomplete and, downstream, the Nationality filter —
// keep this the single source of truth for both so filter values always
// match what candidates could have picked.
export const COUNTRIES: string[] = [
  {ts_list},
];
"""
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"Wrote {len(countries)} countries -> {OUTPUT_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
